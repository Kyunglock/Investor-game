/** 아기 머리 겹. 나(아기 때)는 0번. */
export function babyHair(look: number): Layer {
  const dots =
    BABY_HAIR_DOTS[((look % BABY_HAIR_DOTS.length) + BABY_HAIR_DOTS.length) % BABY_HAIR_DOTS.length]
  return {
    paint: (put, ht) => {
      for (const [dy, x, ch] of dots) {
        put(ht + dy, x, ch)
      }
    },
  }
}

